// Generates TypeScript types + CSP-safe runtime validators from the committed JSON Schema
// contracts in ../shared/schemas (design.md §57: "generated TS types + runtime validator").
//
// Why generated at dev time and committed (like src/api/generated): the Docker build context
// is frontend/ only, so ../shared is not available at image build time; and the production CSP
// (nginx.conf) has no 'unsafe-eval', so Ajv cannot compile schemas in the browser. Ajv's
// "standalone" mode emits plain validation functions instead.
//
// Run: npm run gen:contracts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../shared/schemas");
const outDir = resolve(here, "../src/contracts/generated");

const CONTRACTS = [
  "dashboard_spec",
  "evidence",
  "capability_report",
  "forecast_result",
  "anomaly_result",
  "validation_result",
  "turn_event",
];

const BANNER = "/* eslint-disable */\n// GENERATED by scripts/gen-contracts.mjs from shared/schemas. Do not edit.\n";

mkdirSync(outDir, { recursive: true });

const schemas = Object.fromEntries(
  CONTRACTS.map((name) => [
    name,
    JSON.parse(readFileSync(resolve(schemaDir, `${name}.schema.json`), "utf-8")),
  ]),
);

// 1) Types: one module per contract (their $defs overlap by name, e.g. FieldRef).
for (const [name, schema] of Object.entries(schemas)) {
  const ts = await compile(schema, schema.title, { bannerComment: BANNER, additionalProperties: false });
  writeFileSync(resolve(outDir, `${name}.ts`), ts);
}

// 2) Validators. `discriminator` is an OpenAPI keyword Ajv would reject in strict mode; the
// schema's oneOf already enforces the same thing. Formats (date, date-time) are not checked:
// ponytail: add ajv-formats if a malformed timestamp ever needs to be caught client-side.
const ajv = new Ajv({
  code: { source: true, esm: true },
  strict: false,
  allErrors: true,
  validateFormats: false,
});
for (const [name, schema] of Object.entries(schemas)) ajv.addSchema(schema, name);

const exportsMap = {
  validateDashboardSpec: "dashboard_spec",
  validateKpiCardWidget: "dashboard_spec#/$defs/KpiCardWidget",
  validateChartWidget: "dashboard_spec#/$defs/ChartWidget",
  validateUnavailableWidget: "dashboard_spec#/$defs/UnavailableWidget",
  validateEvidence: "evidence",
  validateCapabilityReport: "capability_report",
  validateForecastResult: "forecast_result",
  validateAnomalyResult: "anomaly_result",
  validateValidationResult: "validation_result",
  validateTurnEvent: "turn_event",
};
writeFileSync(resolve(outDir, "validators.js"), BANNER + standaloneCode(ajv, exportsMap));

const dts = Object.keys(exportsMap)
  .map((fn) => `export declare const ${fn}: ValidateFunction;`)
  .join("\n");
writeFileSync(
  resolve(outDir, "validators.d.ts"),
  `${BANNER}export interface ValidationError {\n  instancePath: string;\n  message?: string;\n}\nexport interface ValidateFunction {\n  (data: unknown): boolean;\n  errors?: ValidationError[] | null;\n}\n${dts}\n`,
);

console.log(`Generated ${CONTRACTS.length} contract type modules + validators into ${outDir}`);
