def _xml_escape(s: str) -> str:
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def _col_letter(idx: int) -> str:
    return chr(ord("A") + idx)


def _cell_xml(col_idx: int, row_idx: int, value) -> str:
    ref = f"{_col_letter(col_idx)}{row_idx}"
    if isinstance(value, dict) and "formula" in value:
        v = value.get("value")
        if isinstance(v, str):
            return f'<c r="{ref}" t="str"><f>{_xml_escape(value["formula"])}</f><v>{_xml_escape(v)}</v></c>'
        return f'<c r="{ref}"><f>{_xml_escape(value["formula"])}</f><v>{v}</v></c>'
    if value is None or value == "":
        return f'<c r="{ref}"/>'
    if isinstance(value, (int, float, Decimal)):
        return f'<c r="{ref}"><v>{value}</v></c>'
    return f'<c r="{ref}" t="inlineStr"><is><t>{_xml_escape(value)}</t></is></c>'


def _sheet_xml(headers: list, rows: list) -> str:
    out = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
           '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>']
    row1 = "".join(_cell_xml(i, 1, h) for i, h in enumerate(headers))
    out.append(f'<row r="1">{row1}</row>')
    for r_idx, row in enumerate(rows, start=2):
        cells = "".join(_cell_xml(i, r_idx, v) for i, v in enumerate(row))
        out.append(f'<row r="{r_idx}">{cells}</row>')
    out.append("</sheetData></worksheet>")
    return "".join(out)


