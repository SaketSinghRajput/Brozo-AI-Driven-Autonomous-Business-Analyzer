def _build_ooxml_zip(path: Path, headers: list, rows: list, macro: bool = False) -> None:
    workbook_ct = ("application/vnd.ms-excel.sheet.macroEnabled.main+xml" if macro
                   else "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml")
    vba_default = '<Default Extension="bin" ContentType="application/vnd.ms-office.vbaProject"/>' if macro else ""
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        f"{vba_default}"
        f'<Override PartName="/xl/workbook.xml" ContentType="{workbook_ct}"/>'
        '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
        '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>'
        "</Types>"
    )
    vba_rel = ('<Relationship Id="rId3" Type="http://schemas.microsoft.com/office/2006/relationships/vbaProject" Target="vbaProject.bin"/>'
               if macro else "")
    workbook_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
        '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>'
        f"{vba_rel}"
        "</Relationships>"
    )
    parts = [
        ("[Content_Types].xml", content_types.encode("utf-8")),
        ("_rels/.rels", _RELS_ROOT_XML.encode("utf-8")),
        ("xl/workbook.xml", _WORKBOOK_XML.encode("utf-8")),
        ("xl/_rels/workbook.xml.rels", workbook_rels.encode("utf-8")),
        ("xl/styles.xml", _STYLES_XML.encode("utf-8")),
        ("xl/worksheets/sheet1.xml", _sheet_xml(headers, rows).encode("utf-8")),
    ]
    if macro:
        parts.append(("xl/vbaProject.bin", _VBA_PLACEHOLDER))

    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, data in parts:
            info = zipfile.ZipInfo(name, date_time=(2024, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            zf.writestr(info, data)


