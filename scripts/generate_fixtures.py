AG_REGIONS = ["North", "South", "East", "West", "Central"]
AG_CROPS = ["Wheat", "Rice", "Cotton", "Sugarcane"]
AG_YEARS = list(range(2019, 2025))  # 6 years
AG_SEASONS = ["Kharif", "Rabi"]     # 2 per year -> 12 season-instances per farm
N_FARMS = 30
CROP_BASE_YIELD = {"Wheat": Decimal("3.2"), "Rice": Decimal("4.0"), "Cotton": Decimal("1.6"), "Sugarcane": Decimal("70.0")}
CROP_COST_PER_HA = {"Wheat": Decimal("28000"), "Rice": Decimal("35000"), "Cotton": Decimal("42000"), "Sugarcane": Decimal("60000")}
CROP_PRICE_PER_T = {"Wheat": Decimal("22000"), "Rice": Decimal("21000"), "Cotton": Decimal("55000"), "Sugarcane": Decimal("3200")}


def gen_agriculture(rng: random.Random) -> dict:
    farms = []
    for i in range(N_FARMS):
        farms.append({
            "farm_id": f"F{i + 1:03d}",
            "region": AG_REGIONS[i % len(AG_REGIONS)],
            "crop": AG_CROPS[i % len(AG_CROPS)],
            "area_ha": Decimal(str(round(rng.uniform(2.0, 25.0), 2))),
        })

    rows, production_by_year, revenue_by_year = [], {}, {}
    for farm in farms:
        for y_idx, year in enumerate(AG_YEARS):
            for season in AG_SEASONS:
                base_yield = CROP_BASE_YIELD[farm["crop"]]
                trend = Decimal(str(1 + 0.02 * y_idx))
                noise = Decimal(str(round(rng.uniform(0.85, 1.15), 4)))
                yield_t_ha = (base_yield * trend * noise).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
                production_t = (farm["area_ha"] * yield_t_ha).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
                cost_noise = Decimal(str(round(rng.uniform(0.9, 1.2), 4)))
                input_cost = d2(farm["area_ha"] * CROP_COST_PER_HA[farm["crop"]] * cost_noise / len(AG_SEASONS))
                price_noise = Decimal(str(round(rng.uniform(0.8, 1.25), 4)))
                price_t = d2(CROP_PRICE_PER_T[farm["crop"]] * price_noise)
                rows.append([
                    farm["farm_id"], farm["region"], farm["crop"], year, season,
                    str(farm["area_ha"]), str(yield_t_ha), str(production_t), str(input_cost), str(price_t),
                ])
                production_by_year[year] = production_by_year.get(year, Decimal("0")) + production_t
                revenue_by_year[year] = revenue_by_year.get(year, Decimal("0")) + d2(production_t * price_t)

    prod_path = FIXTURES / "agriculture" / "production.csv"
    write_csv(prod_path, ["farm_id", "region", "crop", "year", "season", "area_ha", "yield_t_per_ha",
                           "production_t", "input_cost", "market_price_per_t"], rows)

    prod_check, rev_check = {}, {}
    with prod_path.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            y = int(r["year"])
            p = Decimal(r["production_t"])
            prod_check[y] = prod_check.get(y, Decimal("0")) + p
            rev_check[y] = rev_check.get(y, Decimal("0")) + d2(p * Decimal(r["market_price_per_t"]))
    assert prod_check == production_by_year, "agriculture production KPI mismatch between generation and re-read"
    assert rev_check == revenue_by_year, "agriculture revenue KPI mismatch between generation and re-read"

    labels = {
        "dataset": "agriculture",
        "domain": {"expected_status": "known", "primary": "agriculture", "acceptable_alternatives": ["farming"]},
        "tables": {
            "production": {
                "row_count": len(rows),
                "columns": {
                    "farm_id": col("identifier", "identifier"),
                    "region": col("category", "dimension"),
                    "crop": col("category", "dimension"),
                    "year": col("date_part", "time"),
                    "season": col("category", "dimension"),
                    "area_ha": col("quantity", "measure", "additive", "hectare"),
                    "yield_t_per_ha": col("rate_or_ratio", "measure", "non_additive", "t/ha"),
                    "production_t": col("quantity", "measure", "additive", "tonne"),
                    "input_cost": col("currency_amount", "measure", "additive", "currency:INR"),
                    "market_price_per_t": col("price", "measure", "non_additive", "currency:INR/tonne"),
                },
            },
        },
        "entities": [{"name": "Farm", "table": "production", "key": ["farm_id"]}],
        "relationships": [],
        "kpis": {
            "total_production_t_by_year": {
                "formula": "sum(production_t) grouped by year; production_t = area_ha * yield_t_per_ha",
                "unit": "tonne",
                "values": {str(k): str(v) for k, v in sorted(production_by_year.items())},
            },
            "total_revenue_by_year": {
                "formula": "sum(production_t * market_price_per_t) grouped by year",
                "unit": "currency:INR",
                "values": {str(k): str(v) for k, v in sorted(revenue_by_year.items())},
            },
        },
        "available_analyses": ["yield_analysis", "cost_analysis", "profitability", "forecast_seasonal_yearly", "dashboard"],
        "unavailable_analyses": [
            {"analysis": "forecast_daily", "reason_code": "NO_TIME_DIMENSION",
             "message": "Data is at seasonal/yearly grain only; no daily/monthly time dimension is available."},
        ],
        "currency": "INR",
        "generator": {"seed": SEED, "script": "scripts/generate_fixtures.py"},
    }
    write_json(FIXTURES / "agriculture" / "labels.json", labels)
    return {"production": len(rows)}


