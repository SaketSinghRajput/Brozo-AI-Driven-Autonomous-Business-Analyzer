CENT = Decimal("0.01")


def d2(x) -> Decimal:
    """Quantize to 2 decimal places (money), half-up."""
    if not isinstance(x, Decimal):
        x = Decimal(str(x))
    return x.quantize(CENT, rounding=ROUND_HALF_UP)


def write_csv(path: Path, header: list, rows: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, sort_keys=True, ensure_ascii=True)
        f.write("\n")


def month_range(start_y: int, start_m: int, n: int) -> list:
    out = []
    y, m = start_y, start_m
    for _ in range(n):
        out.append((y, m))
        m += 1
        if m == 13:
            m = 1
            y += 1
    return out


def month_str(ym) -> str:
    y, m = ym
    return f"{y:04d}-{m:02d}"


def days_in_month(y: int, m: int) -> int:
    nxt = date(y + 1, 1, 1) if m == 12 else date(y, m + 1, 1)
    return (nxt - date(y, m, 1)).days


def random_date(rng: random.Random, start: date, end: date) -> date:
    span = (end - start).days
    return start + timedelta(days=rng.randint(0, span))


def col(semantic_type: str, role: str, additivity: str = "n/a", unit: str = "unitless") -> dict:
    """One column-label entry (TRD Sec 11.2 semantic types; role: identifier|time|measure|dimension)."""
    return {"semantic_type": semantic_type, "role": role, "additivity": additivity, "unit": unit}


