def make_zip_bomb(path, decompressed_mb: int = 200) -> None:
    """Write a small zip file that decompresses to ~decompressed_mb of zeros.

    Call this from a test, into a tmp directory -- never into evals/fixtures/.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    chunk = b"\x00" * (1024 * 1024)  # 1 MiB, reused each iteration (low peak memory)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        info = zipfile.ZipInfo("zeros.bin", date_time=(2024, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        with zf.open(info, "w") as member:
            for _ in range(decompressed_mb):
                member.write(chunk)


def make_oversized_csv(path, mb: int = 50) -> None:
    """Write a syntactically-valid CSV of approximately `mb` megabytes.

    Call this from a test, into a tmp directory -- never into evals/fixtures/.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    line = "id,category,value,date\n"
    row = "1,Electronics,199.99,2025-01-01\n"
    target_bytes = mb * 1024 * 1024
    with path.open("w", encoding="utf-8", newline="") as f:
        f.write(line)
        written = len(line)
        while written < target_bytes:
            f.write(row)
            written += len(row)


